export const icon = (name, cls = '') => `<svg class="i ${cls}" viewBox="0 0 24 24" aria-hidden="true">${ICONS[name] || ''}</svg>`;

export function esc(value) {
    return String(value ?? '').replace(/[&<>"']/g, (ch) => ({
        '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;',
    })[ch]);
}

/** Salla money values arrive as a number, a numeric string or {amount, currency}. */
export function amount(value) {
    if (value && typeof value === 'object') return Number(value.amount) || 0;
    return Number(value) || 0;
}

export function money(value) {
    const n = amount(value);
    return salla.money ? salla.money(n) : String(n);
}

export function num(n) {
    return salla.helpers?.number ? salla.helpers.number(n) : n;
}

/** The design's stars: five filled/off stars for a 0–5 rating. */
export function stars(rating) {
    const r = Math.round(Number(rating) || 0);
    return `<span class="stars">${Array.from({ length: 5 }, (_, i) => icon('star', i < r ? '' : 'off')).join('')}</span>`;
}

/** The design's toast: dark green pill with a lime check, gone after 3.2s. */
export function toast(message, type, link) {
    let box = document.getElementById('toasts');
    if (!box) {
        box = document.createElement('div');
        box.id = 'toasts';
        box.className = 'toast-wrap az';
        box.setAttribute('aria-live', 'polite');
        document.body.append(box);
    }
    const t = document.createElement('div');
    const isError = type === 'error';
    t.className = 'toast' + (isError ? ' is-error' : '');
    t.setAttribute('role', isError ? 'alert' : 'status');
    t.innerHTML = `${icon(isError ? 'info' : 'check', 'i-sm')}<span>${esc(message)}</span>${link ? `<a href="${esc(link.href)}">${esc(link.text)}</a>` : ''}`;
    box.append(t);
    setTimeout(() => { t.classList.add('out'); setTimeout(() => t.remove(), 300); }, 3200);
}
